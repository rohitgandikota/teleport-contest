// gen-colortable.mjs — embed src/coloratt.c's colortable[] (the enhanced
// colour names) and color_256_definitions[] (the xterm-256 palette) as
// js/coloratt_data.js. Usage: node tools/gen-colortable.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = readFileSync(join(ROOT, 'nethack-c/upstream/src/coloratt.c'), 'utf8');

/* { NHC/NOC/RGBC, tableindex, rgbindex, "name", r, g, b } */
const ct_start = src.indexOf('const struct nethack_color colortable[] = {');
const ct_end = src.indexOf('};', ct_start);
const colortable = [];
const TYP = { NOC: 0 /* no_color */, NHC: 1 /* nh_color */, RGBC: 2 /* rgb_color */ };
for (const m of src.slice(ct_start, ct_end).matchAll(
        /\{\s*(NHC|NOC|RGBC)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*"([^"]*)"\s*,\s*(0x[0-9A-Fa-f]+|\d+)\s*,\s*(0x[0-9A-Fa-f]+|\d+)\s*,\s*(0x[0-9A-Fa-f]+|\d+)\s*\}/g)) {
    colortable.push({ colortyp: TYP[m[1]], tableindex: Number(m[2]),
                      rgbindex: Number(m[3]), name: m[4],
                      r: Number(m[5]), g: Number(m[6]), b: Number(m[7]) });
}
if (colortable.length < 100)
    throw new Error(`colortable: only ${colortable.length} entries parsed`);

const c256_start = src.indexOf('} color_256_definitions[] = {');
const c256_end = src.indexOf('};', c256_start);
const color_256_definitions = [];
for (const m of src.slice(c256_start, c256_end).matchAll(/\{\s*(\d+)\s*,\s*(0x[0-9A-Fa-f]+)\s*\}/g))
    color_256_definitions.push({ index: Number(m[1]), value: Number(m[2]) });
if (color_256_definitions.length < 200)
    throw new Error(`color_256_definitions: only ${color_256_definitions.length} entries parsed`);

const out = `// GENERATED by tools/gen-colortable.mjs from src/coloratt.c — do not edit.
// colortyp: 0 no_color, 1 nh_color, 2 rgb_color (include/color.h:61)

// src/coloratt.c:67 colortable[]
export const colortable = ${JSON.stringify(colortable)};

// src/coloratt.c:888 color_256_definitions[]
export const color_256_definitions = ${JSON.stringify(color_256_definitions)};
`;
writeFileSync(join(ROOT, 'js/coloratt_data.js'), out);
console.log(`wrote js/coloratt_data.js: ${colortable.length} colours, ${color_256_definitions.length} palette entries`);
