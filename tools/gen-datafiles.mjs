// gen-datafiles.mjs — embed the text data files NetHack reads at runtime.
//
// src/rumors.c and src/engrave.c pick a random *byte offset* into dat/rumors
// and dat/engrave and then read forward to the next line. The number of PRNG
// draws depends on where those offsets land, because get_rnd_line() retries up
// to 10 times when it lands on a line longer than MD_PAD_RUMORS. So the port
// cannot approximate this: it needs the files byte for byte.
//
// The judge overlays only js/isaac64.js, js/terminal.js and js/storage.js, and
// there is no build step, so the data has to arrive as an ES module.
//
// Usage: node tools/gen-datafiles.mjs

import { writeFileSync, readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const PROJECT_ROOT = fileURLToPath(new URL('..', import.meta.url));
const RECORDER = join(PROJECT_ROOT, 'nethack-c/recorder');
const OUT = join(PROJECT_ROOT, 'js/dat_files.js');

/* 'data' is the makedefs-built lookup file src/pager.c checkfile() walks for
   farlook "More info?" and the '/'-command typed-word path: line 1 is a
   comment record, line 2 the hex offset of the text section, then index
   patterns with "offset,count" lines, '.' ending the index. Byte offsets
   matter (checkfile fseeks), so it ships verbatim like the rumor files.
   The rest are the '?' help-menu viewers: display_file() pages them as
   NHW_TEXT verbatim (help/hh/history/opthelp/optmenu/usagehlp/license),
   and dowhatdoes() greps cmdhelp for a key's description. */
const FILES = ['rumors', 'engrave', 'epitaph', 'bogusmon', 'data',
               'help', 'hh', 'history', 'opthelp', 'optmenu', 'usagehlp',
               'license', 'cmdhelp', 'keyhelp', 'wizhelp'];

function readDat(name) {
    const path = join(RECORDER, 'dat', name);
    if (!existsSync(path)) return null;
    const buf = readFileSync(path);
    /* Byte offsets must equal string indices, so anything non-ASCII would
       silently shift every fseek. Check rather than assume. */
    for (const b of buf)
        if (b > 0x7f)
            throw new Error(`${name}: non-ASCII byte 0x${b.toString(16)}; `
                + 'the offset model in js/rumors.js assumes 1 byte = 1 char');
    return buf.toString('latin1');
}

// src/rumors.c:96 init_rumors() — the second line carries the ranges.
//   "%d,%ld,%lx;%d,%ld,%lx;0,0,%lx"
function parseRumorsHeader(text) {
    const nl1 = text.indexOf('\n');
    const nl2 = text.indexOf('\n', nl1 + 1);
    const header = text.slice(nl1 + 1, nl2);
    const m = /^(\d+),(\d+),([0-9a-f]+);(\d+),(\d+),([0-9a-f]+);0,0,([0-9a-f]+)$/
        .exec(header.trim());
    if (!m) throw new Error(`rumors: unparsable header ${JSON.stringify(header)}`);
    const true_rumor_size = Number(m[2]);
    const true_rumor_start = parseInt(m[3], 16);
    const false_rumor_size = Number(m[5]);
    const false_rumor_start = parseInt(m[6], 16);
    return {
        true_count: Number(m[1]),
        true_rumor_size,
        true_rumor_start,
        true_rumor_end: true_rumor_start + true_rumor_size,
        false_count: Number(m[4]),
        false_rumor_size,
        false_rumor_start,
        false_rumor_end: false_rumor_start + false_rumor_size,
        eof_offset: parseInt(m[7], 16),
    };
}

function main() {
    if (!existsSync(RECORDER))
        throw new Error('nethack-c/recorder/ not found — run '
            + '`bash nethack-c/build-recorder.sh` first');

    const data = {};
    for (const name of FILES) {
        const text = readDat(name);
        if (text !== null) data[name] = text;
    }
    if (!data.rumors) throw new Error('dat/rumors not found');

    const hdr = parseRumorsHeader(data.rumors);
    if (hdr.eof_offset !== data.rumors.length)
        throw new Error(`rumors: header eof ${hdr.eof_offset} != file length `
            + `${data.rumors.length}`);

    const out = `// dat_files.js — GENERATED by tools/gen-datafiles.mjs.
// Do not edit by hand; re-run the generator.
//
// Verbatim contents of the dat/ text files that src/rumors.c and
// src/engrave.c read at runtime. get_rnd_line() seeks to a random byte offset
// and retries when the line it lands on is too long, so the number of PRNG
// draws depends on the exact bytes. These are ASCII-only, checked by the
// generator, so string index == byte offset.
//
// Lines are xcrypt()-obfuscated in the file; js/rumors.c's xcrypt() undoes it.

${Object.entries(data).map(([k, v]) =>
    `export const ${k} = ${JSON.stringify(v)};`).join('\n\n')}

// src/rumors.c:96 init_rumors() — parsed from the file's own header line.
export const RUMOR_RANGES = ${JSON.stringify(hdr, null, 1)};
`;

    writeFileSync(OUT, out);
    console.log(`wrote ${OUT}`);
    for (const [k, v] of Object.entries(data))
        console.log(`  ${k}: ${v.length} bytes`);
    console.log(`  true rumors  ${hdr.true_count} @ ${hdr.true_rumor_start}`
        + `..${hdr.true_rumor_end} (${hdr.true_rumor_size})`);
    console.log(`  false rumors ${hdr.false_count} @ ${hdr.false_rumor_start}`
        + `..${hdr.false_rumor_end} (${hdr.false_rumor_size})`);
}

main();
