#!/usr/bin/env node
// gen-questtext.mjs — embed dat/quest.lua's `questtext` table as js/quest_data.js
//
// src/questpgr.c com_pager_core() reads dat/quest.lua through the Lua
// interpreter. Until that interpreter exists we still need the exact strings,
// and hand-transcribing 3,000 lines of nested Lua tables is how transcription
// errors get in. So load the file with the REAL Lua binary the recorder build
// downloaded and serialise the result.
//
// Usage: node tools/gen-questtext.mjs
//
// Requires nethack-c/recorder/lib/lua-5.4.8/src/lua, which build-recorder.sh
// produces. The output is checked in, so this only needs re-running when the
// upstream quest.lua changes.

import { execFileSync } from 'node:child_process';
import { writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const LUA = join(ROOT, 'nethack-c/recorder/lib/lua-5.4.8/src/lua');
const QUEST = join(ROOT, 'nethack-c/upstream/dat/quest.lua');
const OUT = join(ROOT, 'js/quest_data.js');

if (!existsSync(LUA)) {
    console.error(`missing ${LUA}\nrun nethack-c/build-recorder.sh first`);
    process.exit(2);
}

// A minimal JSON encoder in Lua: quest.lua holds only tables, strings and
// numbers, so this covers it. Arrays are the random-message lists, which must
// keep their order because com_pager_core indexes them with rn2(nelems) + 1.
const DUMPER = `
local function esc(s)
  return (s:gsub('[%c"\\\\]', function(c)
    if c == '"' then return '\\\\"' end
    if c == '\\\\' then return '\\\\\\\\' end
    if c == '\\n' then return '\\\\n' end
    if c == '\\t' then return '\\\\t' end
    if c == '\\r' then return '\\\\r' end
    return string.format('\\\\u%04x', c:byte())
  end))
end
local enc
local function isarray(t)
  local n = 0
  for k in pairs(t) do
    if type(k) ~= 'number' then return false end
    n = n + 1
  end
  return n == #t and n > 0
end
enc = function(v)
  local ty = type(v)
  if ty == 'string' then return '"' .. esc(v) .. '"' end
  if ty == 'number' or ty == 'boolean' then return tostring(v) end
  if ty ~= 'table' then error('unsupported type ' .. ty) end
  local parts = {}
  if isarray(v) then
    for i = 1, #v do parts[#parts + 1] = enc(v[i]) end
    return '[' .. table.concat(parts, ',') .. ']'
  end
  local keys = {}
  for k in pairs(v) do keys[#keys + 1] = k end
  table.sort(keys, function(a, b) return tostring(a) < tostring(b) end)
  for _, k in ipairs(keys) do
    parts[#parts + 1] = '"' .. esc(tostring(k)) .. '":' .. enc(v[k])
  end
  return '{' .. table.concat(parts, ',') .. '}'
end
dofile(arg[1])
io.write(enc(questtext))
`;

const json = execFileSync(LUA, ['-', QUEST], { input: DUMPER, encoding: 'utf8',
                                               maxBuffer: 64 * 1024 * 1024 });
const questtext = JSON.parse(json);

const sections = Object.keys(questtext);
const ids = sections.reduce(
    (n, s) => n + (typeof questtext[s] === 'object' ? Object.keys(questtext[s]).length : 0), 0);

const body = `// quest_data.js — GENERATED by tools/gen-questtext.mjs. Do not edit.
// Source: dat/quest.lua, loaded with the real Lua 5.4.8 interpreter.
//
// src/questpgr.c com_pager_core() looks up questtext[section][msgid]; the
// section is "common" or a role's filecode ("Arc", "Bar", ...). Each entry
// carries some of { text, synopsis, output }, or is an array of strings that
// the caller picks from with rn2(#array) + 1 — so the array ORDER is part of
// the PRNG contract, not a presentation detail.
//
// ${sections.length} sections, ${ids} message ids.

export const questtext = ${JSON.stringify(questtext, null, 1)};
`;

writeFileSync(OUT, body);
console.log(`wrote ${OUT}: ${sections.length} sections, ${ids} ids, `
            + `${body.length} bytes`);
